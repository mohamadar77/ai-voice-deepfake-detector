"""Structured logging and request context, without audio or personal data.

Log fields are an allowlist, and string values must be short identifiers. Nothing
derived from the upload (filename, bytes, hashes of audio) and no score, decision
or client address is ever logged. A request id is generated by the server; an id
sent by a client is ignored.
"""

from __future__ import annotations

import json
import logging
import math
import re
import sys
import time
import uuid
from datetime import UTC, datetime
from typing import Any

from starlette.datastructures import MutableHeaders

REQUEST_ID_KEY = "voice_detector.request_id"
LOGGER_NAME = "voice_detector.serving"

ALLOWED_FIELDS = frozenset(
    {
        "request_id", "route", "status", "error_code", "error_type", "queue_ms", "decode_ms",
        "inference_ms", "total_ms", "duration_s", "n_windows", "warning_codes", "model_version",
        "bundle_hash", "config_sha256", "host", "port", "warmup_ms", "reason",
    }
)
_SAFE_TEXT = re.compile(r"^[A-Za-z0-9_.:/\-]{0,64}$")
_logger = logging.getLogger(LOGGER_NAME)


def _clean(value: Any) -> Any:
    if value is None or isinstance(value, bool):
        return value
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, str):
        return value if _SAFE_TEXT.match(value) else "redacted"
    if isinstance(value, list | tuple):
        return [_clean(item) for item in value]
    return "redacted"


def log_event(event: str, *, level: int = logging.INFO, **fields: Any) -> None:
    """Emit one JSON log line. Unknown field names raise (a programming error)."""

    unknown = set(fields) - ALLOWED_FIELDS
    if unknown:
        raise ValueError(f"log field(s) not allowed: {sorted(unknown)}")
    if not _SAFE_TEXT.match(event):
        raise ValueError("log event name must be a short identifier")
    record = {"ts": datetime.now(UTC).isoformat(timespec="milliseconds"), "event": event}
    record.update({key: _clean(value) for key, value in fields.items()})
    _logger.log(level, json.dumps(record, sort_keys=True))


class _StripTraceback(logging.Filter):
    """Drop exception text so a traceback can never carry request data into a log."""

    def filter(self, record: logging.LogRecord) -> bool:
        record.exc_info = None
        record.exc_text = None
        record.stack_info = None
        return True


def configure_logging(level: str, *, debug_tracebacks: bool) -> None:
    """Route service and uvicorn logs to stderr as plain lines; strip tracebacks."""

    handler = logging.StreamHandler(sys.stderr)
    handler.setFormatter(logging.Formatter("%(message)s"))
    if not debug_tracebacks:
        handler.addFilter(_StripTraceback())
    for name in (LOGGER_NAME, "uvicorn", "uvicorn.error"):
        target = logging.getLogger(name)
        target.handlers = [handler]
        target.setLevel(level)
        target.propagate = False


class RequestContextMiddleware:
    """Pure ASGI: request id, response headers and one completion log per request."""

    def __init__(self, app: Any, *, known_paths: frozenset[str]) -> None:
        self.app = app
        self.known_paths = known_paths

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        request_id = str(uuid.uuid4())
        scope[REQUEST_ID_KEY] = request_id
        status = 500
        started = time.perf_counter()

        async def send_with_headers(message: Any) -> None:
            nonlocal status
            if message["type"] == "http.response.start":
                status = int(message["status"])
                headers = MutableHeaders(scope=message)
                headers["X-Request-ID"] = request_id
                headers["Cache-Control"] = "no-store"
                headers["X-Content-Type-Options"] = "nosniff"
            await send(message)

        try:
            await self.app(scope, receive, send_with_headers)
        finally:
            path = scope.get("path", "")
            log_event(
                "request",
                request_id=request_id,
                route=path if path in self.known_paths else "unmatched",
                status=status,
                total_ms=round((time.perf_counter() - started) * 1000.0, 3),
            )
